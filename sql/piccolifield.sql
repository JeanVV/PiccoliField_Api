DROP DATABASE IF EXISTS piccoliField_db;
CREATE DATABASE piccoliField_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE piccoliField_db;

-- 1. ESTRUCTURA GEOGRÁFICA
CREATE TABLE DEPARTAMENTO (
    idDepartamento INT AUTO_INCREMENT PRIMARY KEY,
    departamento VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE PROVINCIA (
    idProvincia INT AUTO_INCREMENT PRIMARY KEY,
    provincia VARCHAR(100) NOT NULL,
    idDepartamento INT NOT NULL,
    FOREIGN KEY (idDepartamento) REFERENCES DEPARTAMENTO(idDepartamento) ON DELETE CASCADE
);

CREATE TABLE DISTRITO (
    idDistrito INT AUTO_INCREMENT PRIMARY KEY,
    distrito VARCHAR(100) NOT NULL,
    idProvincia INT NOT NULL,
    FOREIGN KEY (idProvincia) REFERENCES PROVINCIA(idProvincia) ON DELETE CASCADE
);

-- 2. CATÁLOGO DE PRODUCTOS
CREATE TABLE PRODUCTOS (
    idProductos INT AUTO_INCREMENT PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    codigo_ean VARCHAR(50) UNIQUE,
    producto VARCHAR(150) NOT NULL,
    categoria VARCHAR(100) NOT NULL,
    descripcion TEXT,
    url_foto VARCHAR(255),
    estado ENUM('ACTIVO', 'INACTIVO') NOT NULL DEFAULT 'ACTIVO'
);

-- 3. SEDES DE LA EMPRESA
CREATE TABLE SEDES (
    idSede INT AUTO_INCREMENT PRIMARY KEY,
    sede VARCHAR(150) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    codHuellero VARCHAR(50) UNIQUE,
    latitud DECIMAL(10, 8) NOT NULL,
    longitud DECIMAL(11, 8) NOT NULL,
    radio_geocerca DECIMAL(6, 2) NOT NULL DEFAULT 100.00,
    idDistrito INT NOT NULL,
    FOREIGN KEY (idDistrito) REFERENCES DISTRITO(idDistrito)
);

-- 4. USUARIOS (TRABAJADORES)
CREATE TABLE USUARIOS (
    idUsuario INT AUTO_INCREMENT PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    apePaterno VARCHAR(100) NOT NULL,
    apeMaterno VARCHAR(100) NOT NULL, 
    correo VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol ENUM('ADMINISTRADOR', 'PROMOTOR', 'IMPULSADOR', 'TRABAJADOR') NOT NULL,
    fcm_token VARCHAR(255) NULL,
    id_dispositivo VARCHAR(100) NULL, 
    estado ENUM('ACTIVO', 'INACTIVO') NOT NULL DEFAULT 'ACTIVO',
    url_foto VARCHAR(255) NULL,
    meta_ventas INT NOT NULL DEFAULT 0,
    idDistrito INT NOT NULL,
    idSede INT NOT NULL,
    FOREIGN KEY (idDistrito) REFERENCES DISTRITO(idDistrito),
    FOREIGN KEY (idSede) REFERENCES SEDES(idSede)
);

-- 5. PUNTOS DE VENTA 
CREATE TABLE PUNTOS_VENTA (
    idPuntosVenta INT AUTO_INCREMENT PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    puntoVenta VARCHAR(150) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    estado ENUM('ACTIVO', 'INACTIVO', 'CLAUSURADO') NOT NULL DEFAULT 'ACTIVO',
    latitud DECIMAL(10, 8) NOT NULL,
    longitud DECIMAL(11, 8) NOT NULL,
    radio_geocerca DECIMAL(6, 2) NOT NULL DEFAULT 50.00,
    tipo ENUM('VENTA', 'DISTRIBUCIÓN') NOT NULL,
    idDistrito INT NOT NULL,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idDistrito) REFERENCES DISTRITO(idDistrito),
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 6. ASISTENCIAS
CREATE TABLE ASISTENCIAS (
    idAsistencias INT AUTO_INCREMENT PRIMARY KEY,
    tipo ENUM('INGRESO', 'SALIDA') NOT NULL,
    fecha_hora_servidor DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_hora_dispositivo DATETIME NOT NULL,
    estado ENUM('A_TIEMPO', 'TARDANZA', 'FALTA') NOT NULL DEFAULT 'A_TIEMPO',
    minutos_tardanza INT NOT NULL DEFAULT 0,
    latitud DECIMAL(10, 8) NULL,
    longitud DECIMAL(11, 8) NULL,
    radio DECIMAL(10, 2) NULL,
    precision_m DECIMAL(6, 2) NULL,
    marcacion_observada TINYINT(1) NOT NULL DEFAULT 0,
    observacion VARCHAR(255) NULL,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 7. JUSTIFICACIONES DE ASISTENCIA
CREATE TABLE JUSTIFICACIONES (
    idJustificacion INT AUTO_INCREMENT PRIMARY KEY,
    motivo VARCHAR(100) NOT NULL,
    descripcion TEXT NOT NULL,
    ruta_sustento VARCHAR(255) NULL,
    estado ENUM('PENDIENTE', 'APROBADA', 'RECHAZADA') NOT NULL DEFAULT 'PENDIENTE',
    fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_revision DATETIME NULL,
    comentario_revision TEXT NULL,
    idAsistencias INT NOT NULL UNIQUE,
    idUsuario INT NOT NULL,
    idRevisor INT NULL,
    FOREIGN KEY (idAsistencias) REFERENCES ASISTENCIAS(idAsistencias) ON DELETE CASCADE,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario),
    FOREIGN KEY (idRevisor) REFERENCES USUARIOS(idUsuario)
);

-- 8. PROSPECTOS
CREATE TABLE PROSPECTOS (
    idProspectos INT AUTO_INCREMENT PRIMARY KEY,
    nombre_comercial VARCHAR(200) NOT NULL,
    tipo_local VARCHAR(100) NULL,
    direccion VARCHAR(255) NOT NULL,
    contacto VARCHAR(150) NULL,
    telefono VARCHAR(20) NULL,
    potencial ENUM('ALTO', 'MEDIO', 'BAJO') NOT NULL DEFAULT 'MEDIO',
    estado ENUM('NUEVO', 'EN_NEGOCIACION', 'CONVERTIDO', 'DESCARTADO') NOT NULL DEFAULT 'NUEVO',
    notas TEXT NULL,
    motivo_descarte VARCHAR(255) NULL,
    url_foto VARCHAR(255) NULL,
    latitud DECIMAL(10, 8) NOT NULL,
    longitud DECIMAL(11, 8) NOT NULL,
    fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre DATETIME NULL,
    idUsuario INT NOT NULL,
    idDistrito INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario),
    FOREIGN KEY (idDistrito) REFERENCES DISTRITO(idDistrito)
);

-- 9. SEGUIMIENTO DE PROSPECTOS
CREATE TABLE SEGUIMIENTOS_PROSPECTO (
    idSeguimiento INT AUTO_INCREMENT PRIMARY KEY,
    tipo ENUM('LLAMADA', 'VISITA', 'MENSAJE', 'PROPUESTA') NOT NULL,
    comentario TEXT NOT NULL,
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    proxima_accion VARCHAR(255) NULL,
    fecha_proxima_accion DATE NULL,
    idProspectos INT NOT NULL,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idProspectos) REFERENCES PROSPECTOS(idProspectos) ON DELETE CASCADE,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 10. INCIDENCIAS
CREATE TABLE INCIDENCIAS (
    idIncidencias INT AUTO_INCREMENT PRIMARY KEY,
    tipo VARCHAR(100) NOT NULL,
    severidad ENUM('ALTA', 'MEDIA', 'BAJA') NOT NULL DEFAULT 'MEDIA',
    descripcion TEXT NOT NULL,
    estado ENUM('ABIERTO', 'EN_PROCESO', 'RESUELTO') NOT NULL DEFAULT 'ABIERTO',
    fecha_registro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    comentario_atencion TEXT NULL,
    fecha_atencion DATETIME NULL,
    idUsuario INT NOT NULL,
    idPuntosVenta INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario),
    FOREIGN KEY (idPuntosVenta) REFERENCES PUNTOS_VENTA(idPuntosVenta)
);

-- 11. ALERTAS DE STOCK
CREATE TABLE ALERTAS_STOCK (
    idAlertas INT AUTO_INCREMENT PRIMARY KEY,
    tipo VARCHAR(100) NOT NULL,
    estado ENUM('PENDIENTE', 'ATENDIDA', 'IGNORADA') NOT NULL DEFAULT 'PENDIENTE',
    comentario TEXT NULL,
    fechaAtencion DATE NULL,
    fechaEmision DATE NOT NULL DEFAULT (CURRENT_DATE),
    severidad ENUM('ALTA', 'MEDIA', 'BAJA') NOT NULL DEFAULT 'MEDIA',
    horaAtencion TIME NULL,
    horaEmision TIME NOT NULL DEFAULT (CURRENT_TIME),
    idProductos INT NOT NULL,
    idPuntosVenta INT NOT NULL,
    FOREIGN KEY (idProductos) REFERENCES PRODUCTOS(idProductos),
    FOREIGN KEY (idPuntosVenta) REFERENCES PUNTOS_VENTA(idPuntosVenta)
);

-- 12. PRODUCTOS POR PUNTO DE VENTA
CREATE TABLE PDV_PRODUCTOS (
    idPuntosVenta INT NOT NULL,
    idProductos INT NOT NULL,
    stock_minimo INT NOT NULL DEFAULT 0,
    PRIMARY KEY (idPuntosVenta, idProductos),
    FOREIGN KEY (idPuntosVenta) REFERENCES PUNTOS_VENTA(idPuntosVenta),
    FOREIGN KEY (idProductos) REFERENCES PRODUCTOS(idProductos)
);

-- 13. PEDIDO (RENDIMIENTO)
CREATE TABLE Pedido (
    idPedido INT AUTO_INCREMENT PRIMARY KEY,
    cantSolicitada INT NOT NULL CHECK (cantSolicitada > 0),
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado ENUM('REGISTRADO', 'EN_PREPARACION', 'ENTREGADO', 'CANCELADO') NOT NULL DEFAULT 'REGISTRADO',
    idPuntosVenta INT NOT NULL,
    idProductos INT NOT NULL,
    FOREIGN KEY (idPuntosVenta) REFERENCES PUNTOS_VENTA(idPuntosVenta),
    FOREIGN KEY (idProductos) REFERENCES PRODUCTOS(idProductos)
);

-- 14. REGISTROS DE STOCK
CREATE TABLE STOCK_REGISTROS (
    idStock INT AUTO_INCREMENT PRIMARY KEY,
    cant_exhibida INT NOT NULL DEFAULT 0,
    cant_almacen INT NOT NULL DEFAULT 0,
    estadoStock ENUM('OPTIMO', 'BAJO', 'AGOTADO') NOT NULL,
    observacion TEXT NULL,
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    stock_minimo INT NOT NULL DEFAULT 0,
    idPedido INT NOT NULL,
    FOREIGN KEY (idPedido) REFERENCES Pedido(idPedido) ON DELETE CASCADE
);

-- 15. EVIDENCIAS FOTOGRÁFICAS
CREATE TABLE EVIDENCIAS (
    idEvidencias INT AUTO_INCREMENT PRIMARY KEY,
    ruta_archivo VARCHAR(255) NOT NULL,
    hash_sha VARCHAR(64) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    fecha_captura DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idStock INT NULL,
    idIncidencias INT NULL,
    FOREIGN KEY (idStock) REFERENCES STOCK_REGISTROS(idStock) ON DELETE CASCADE,
    FOREIGN KEY (idIncidencias) REFERENCES INCIDENCIAS(idIncidencias) ON DELETE CASCADE
);

-- 16. VENTAS
CREATE TABLE VENTAS (
    idVenta INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    total DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 17. DETALLE_VENTA
CREATE TABLE DETALLE_VENTA (
    idVenta INT NOT NULL,
    idProductos INT NOT NULL,
    precio DECIMAL(10, 2) NOT NULL,
    cantidad INT NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (idVenta, idProductos),
    FOREIGN KEY (idVenta) REFERENCES VENTAS(idVenta) ON DELETE CASCADE,
    FOREIGN KEY (idProductos) REFERENCES PRODUCTOS(idProductos)
);

-- 18. HISTORIAL DE ASIGNACIONES DE PUNTOS DE VENTA
CREATE TABLE HISTORIAL_ASIGNACIONES (
    idHistorial INT AUTO_INCREMENT PRIMARY KEY,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NULL,
    motivo VARCHAR(255) NULL,
    idPuntosVenta INT NOT NULL,
    idUsuario INT NOT NULL,
    idUsuarioRegistra INT NOT NULL,
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    FOREIGN KEY (idPuntosVenta) REFERENCES PUNTOS_VENTA(idPuntosVenta),
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario),
    FOREIGN KEY (idUsuarioRegistra) REFERENCES USUARIOS(idUsuario)
);

-- 19. OPERACIONES SINCRONIZADAS 
CREATE TABLE OPERACIONES_SYNC (
    idOperacion CHAR(36) PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL,
    resultado_json JSON NULL,
    fecha_proceso DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 20. LOG DE NOTIFICACIONES
CREATE TABLE NOTIFICACIONES_LOG (
    idNotificacion INT AUTO_INCREMENT PRIMARY KEY,
    tipo VARCHAR(50) NOT NULL,
    referencia VARCHAR(100) NULL,
    mensaje VARCHAR(255) NOT NULL,
    fcm_result VARCHAR(255) NULL,
    fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idUsuario INT NOT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);

-- 21. CONFIGURACIÓN DEL SISTEMA (hora de inicio por rol, tolerancias, radios y umbrales)
CREATE TABLE CONFIGURACION (
    clave VARCHAR(100) PRIMARY KEY,
    valor VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255) NULL,
    fecha_actualizacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idUsuario INT NULL,
    FOREIGN KEY (idUsuario) REFERENCES USUARIOS(idUsuario)
);